#!/usr/bin/env bash
# Уход из сессии: гибернация, выключение, перезагрузка.
#
#     power.sh            -- гибернация (по умолчанию)
#     power.sh poweroff   -- выключение
#     power.sh reboot     -- перезагрузка
#     power.sh lock       -- заблокировать экран
#
# Перед любым из трёх снимаем снимок сессии. Гибернация возвращает всё сама, и
# снимок ей не нужен -- он нужен на случай, когда она не случилась: не хватило
# swap, не проснулся драйвер, выдернули питание. Тогда сессию поднимет
# session-restore.sh, пусть и без вкладок.
#
# Гибернация против выключения: гибернация сохраняет память целиком, поэтому
# после неё возвращаются и вкладки браузера, и несохранённые буферы. Скрипт
# сессии так не умеет в принципе -- он знает только, какие программы были
# открыты и где.

set -uo pipefail

VXWM_DIR=$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")

notify() { command -v notify-send >/dev/null 2>&1 && notify-send -u critical "vxwm" "$1"; }

action=${1:-hibernate}

# Блокировка. slock держит экран, пока не введён пароль; запускаем его фоном и
# даём успеть отрисоваться, иначе гибернация случится раньше, чем появится
# замок, и на долю секунды после пробуждения мелькнёт рабочий стол.
lock_screen() {
    command -v slock >/dev/null 2>&1 || return 0
    pgrep -x slock >/dev/null && return 0
    slock &
    sleep 0.4
}

if [ "$action" = "lock" ]; then
    lock_screen
    exit 0
fi

# Снимок берём синхронно: после systemctl hibernate процессы замирают, и
# фоновый снимок не успел бы дописать файл.
"$VXWM_DIR/session-save.sh"

case $action in
    hibernate)
        # Пустой swap -- верный признак, что hibernate-setup.sh ещё не
        # запускали. Молча выключаться в таком случае нельзя: человек ждал
        # сохранения сессии, а получил бы потерю всего несохранённого.
        if [ "$(swapon --show --noheadings 2>/dev/null)" = "" ]; then
            notify "Гибернация недоступна: нет swap. Запусти vxwm/hibernate-setup.sh"
            exit 1
        fi
        # Блокируем до засыпания, а не после пробуждения: иначе между
        # появлением картинки и замком есть окно, в котором видно рабочий стол.
        lock_screen
        systemctl hibernate || {
            notify "Гибернация не удалась, сессия осталась на месте"
            exit 1
        }
        ;;
    poweroff | reboot)
        systemctl "$action"
        ;;
    *)
        echo "использование: $0 [hibernate|poweroff|reboot|lock]" >&2
        exit 2
        ;;
esac
