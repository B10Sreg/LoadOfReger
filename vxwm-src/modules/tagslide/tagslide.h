/* Листание тегов: окна старого тега уезжают за край, окна нового приезжают
 * из-за противоположного.
 *
 * Сами кадры считает не WM, а композитор. Мы только переставляем окна в две
 * точки -- "за краем" и "на месте" -- а picom догоняет новое положение своей
 * пружиной (animation-stiffness-in-tag в picom.conf). Условие у него одно:
 * окно должно оставаться замапленным, тогда смена координат попадает в
 * ветку ANIM_IN_TAG (src/win.c). Поэтому уезжающие окна размапливаются не
 * сразу, а через TAG_SLIDE_MS, когда анимация уже отыграла.
 *
 * Так было не всегда: прошлая версия рисовала переход сама -- nanosleep по
 * кадрам и XGrabServer на стыке. Ценой был замерший на ~40 мс экран посреди
 * перехода и необработанный ввод всё это время. Здесь нет ни того, ни другого:
 * функции только ставят окна и возвращают управление, а дозировку по времени
 * держит планировщик в run().
 *
 * Порядок на одно переключение тега:
 *
 *   view()  -> tagslide_out()  окна старого тега сдвигаются за край и метятся
 *                              TS_OUT; showhide видит метку и не размапливает
 *                              их (см. SHOWHIDEPROFILE в vxwm.c)
 *           -> arrange()       окна нового тега мапятся и встают на места
 *           -> tagslide_in()   они тут же сдвигаются за противоположный край
 *                              и метятся TS_IN
 *   run()   -> tagslide_tick() через TS_IN_DELAY_MS ставит TS_IN на места
 *                              (это и есть приезд), через TAG_SLIDE_MS
 *                              размапливает TS_OUT
 *
 * Зачем задержка перед приездом: picom склеивает все события, пришедшие в один
 * проход цикла. Поставь окно на место сразу -- он увидит только конечную
 * позицию, анимировать будет нечего. Ему нужен хотя бы один отрисованный кадр
 * с окном за краем, отсюда TS_IN_DELAY_MS чуть больше кадра.
 */

#define TS_IDLE 0
#define TS_OUT  1  /* уехало за край, ждёт размапливания */
#define TS_IN   2  /* стоит за краем, ждёт въезда */

/* Кадр при 60 Гц -- 16 мс; берём с запасом, чтобы picom наверняка успел
 * отрисовать окно за краем до того, как мы двинем его на место. */
#define TS_IN_DELAY_MS 24

